/**
 * loraIndex.ts
 *
 * What the installed LoRAs say about themselves, read out of their own files.
 *
 *
 * THE MEASUREMENT THIS FILE EXISTS FOR.
 *
 * A LoRA whose trigger word is missing from the prompt is substantially weaker.
 * Measured here on Pony V6, same seed, add-micro-details at strength 0.6,
 * whole-frame Laplacian variance:
 *
 *     base, no LoRA                    165.9   1.000x
 *     add-micro-details, no trigger    269.5   1.625x
 *     add-micro-details, with trigger  353.8   2.132x
 *
 * Loading the weights gets 1.625x. Saying the word on top of that is worth a
 * further 1.313x, and it changes 67 percent of the pixels. Roughly a third of
 * what a LoRA can do is sitting behind one token.
 *
 * Any earlier per LoRA figure in this project that was taken without triggers is
 * therefore a FLOOR, not a result: it understates its LoRA by about a third.
 * Anywhere such a number is shown, it has to be labelled as a floor.
 *
 *
 * WHERE THE DATA COMES FROM.
 *
 * Not from a web page and not from a human retyping a token. Every LoRA trained
 * with kohya-ss sd-scripts carries `ss_tag_frequency` in its safetensors header:
 * the real caption tag distribution of its training set, with counts. A tag that
 * is in nearly every training image and in no other LoRA on disk is, by
 * construction, the token the author minted for this one.
 *
 * scripts/index-loras.ts reads those headers and regenerates the block at the
 * bottom of this file. Run `npm run index-loras` after downloading LoRAs. The
 * hand-written half, the types and the queries, is above the marker and survives.
 *
 * This already caught one error: src/lib/loras.ts records `rnat` for
 * real-nipples-and-areola-textures, and the file says `rnct`.
 *
 *
 * WHAT IT DOES NOT KNOW, AND SAYS SO.
 *
 * Of the 61 files installed, 11 carry no metadata block at all and 11 more carry
 * metadata with no tag frequency, leaving 39 taggable. `hasMetadata` and
 * `hasTagFrequency` record that, and `confidence` is `no-data` for the other 22. They are not broken, and it is not the same
 * thing as having no trigger:
 *
 *     confidence 'no-data'  the file does not say. Show "no trigger data".
 *     confidence 'none'     the file does say, and the answer is no trigger.
 *
 * Collapsing those two into "no trigger needed" is the error this file is built
 * to prevent, because it silently drops a third of the effect from every LoRA
 * that shipped a bare header.
 *
 * `confidence` on the rest runs strong, likely, weak. Weak means the extraction
 * rests on thin captions or on the dataset folder name, and `notes` says exactly
 * why in plain words. Read notes before putting a weak trigger in a prompt: a
 * wrong trigger poisons the prompt with a token the model has no meaning for,
 * which is worse than leaving it out.
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

/**
 * The weight family a LoRA was actually trained against. Deliberately the same
 * names as `LoraArch` in ./loras.ts, minus the architectures nothing on disk
 * targets, so the two tables join on this field without a translation step.
 */
export type IndexedBase = 'pony' | 'illustrious' | 'sdxl' | 'flux1d' | 'sd15' | 'wan' | 'unknown'

/** How a candidate trigger was recognised. */
export type TriggerKind =
  /** A minted token: digits substituted into letters, used by this LoRA alone. p3p05y, v4n1lla. */
  | 'invented'
  /** Ordinary words, but in nearly every caption and rare across the rest of the folder. */
  | 'phrase'
  /** A Pony quality prefix such as score_9. Real, but deduplicate it against your own preamble. */
  | 'quality'
  /** From the training folder name, because no caption tag was near universal. Weakest. */
  | 'folder'

export type TriggerConfidence =
  /** A minted token in nearly every caption. As close to certain as the file can get. */
  | 'strong'
  /** A near universal tag that no other LoRA here uses. Very probably right. */
  | 'likely'
  /** Thin captions, or the folder name only. Read `notes` before using it. */
  | 'weak'
  /** The file has tag data and none of it is a trigger. This LoRA runs on weight alone. */
  | 'none'
  /** The file ships no tag data. Unknown, which is not the same as none. */
  | 'no-data'

export type LoraTrigger = {
  /** The token exactly as the training captions spell it. */
  tag: string
  /** Training images carrying it, summed across dataset buckets. */
  count: number
  /** count divided by the image count, 0 to 1. */
  share: number
  kind: TriggerKind
  /** True when no other indexed LoRA uses this tag at all. The strongest single signal. */
  uniqueToThisLora: boolean
}

/**
 * An informative tag below the trigger bar, with how much of the training set
 * carried it. This is what prompt matching scores against: the LoRA's own
 * statement of what it was shown. Generic booru filler is already stripped out.
 */
export type LoraConcept = { tag: string; count: number; share: number }

export type LoraIndexEntry = {
  /** Filename as LoraLoader.lora_name lists it. Joins to /api/models and to loras.ts `file`. */
  file: string
  /** Filename without the extension, for display. */
  stem: string
  bytes: number
  /** The base the weights were trained on, not the one the filename advertises. */
  base: IndexedBase
  /** Plain words for why `base` says what it says. Show this when a user disagrees with it. */
  baseEvidence: string
  /** Other families the filename or the author's title claims, which the file does not support. */
  nameClaims: IndexedBase[]
  /** ss_sd_model_name: the checkpoint it was trained on. Often a bare Civitai id, sometimes empty. */
  trainedOn: string
  /** The author's own name for it, from modelspec.title or ss_output_name. */
  authorName: string
  /** LoRA rank. 0 when the file does not say. */
  networkDim: number
  /** False when the safetensors header has no `__metadata__` block at all. */
  hasMetadata: boolean
  /** False when there is metadata but no ss_tag_frequency, so no trigger can be recovered. */
  hasTagFrequency: boolean
  /** Largest summed tag count, used as the training image count. 0 when unknown. */
  imageCount: number
  /** kohya dataset bucket names, `<repeats>_<concept>`. Sometimes the only trigger evidence. */
  datasetFolders: string[]
  triggers: LoraTrigger[]
  /**
   * The subset of `triggers` that belongs in a prompt, in order.
   *
   * When the LoRA minted a token, that token is the whole trigger and the rest of
   * its near universal tags are the author's caption template, which dilutes the
   * prompt rather than helping it. real-nipples captions `rnct` alongside
   * "realistic nipples textures, nipples textures, areola textures, realism", and
   * only `rnct` is the address. When nothing was minted, every near universal tag
   * goes in, because then the template is all the evidence there is.
   *
   * `triggers` keeps the full list either way, for anyone who wants to see it.
   */
  promptTags: string[]
  /** `promptTags` joined with commas, ready to paste. Empty string when there are none. */
  triggerPhrase: string
  confidence: TriggerConfidence
  concepts: LoraConcept[]
  /** Honest caveats about this particular extraction. Worth showing when confidence is weak. */
  notes: string[]
}

