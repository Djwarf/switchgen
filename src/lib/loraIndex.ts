// Prompt matching
// ---------------------------------------------------------------------------

export type ConceptHit = {
  /** The indexed tag that matched, in the LoRA's own spelling. */
  tag: string
  /** Share of that LoRA's training images carrying it. */
  share: number
  /** Whether the hit landed on a trigger or on an ordinary concept. */
  via: 'trigger' | 'concept'
}

export type LoraMatch = {
  entry: LoraIndexEntry
  /**
   * Sum over matched tags of share times a word count bonus. Not a probability
   * and not calibrated against anything: it orders candidates, nothing more.
   */
  score: number
  hits: ConceptHit[]
}

type Posting = { file: string; share: number; via: 'trigger' | 'concept'; words: number }

let postings: Map<string, Posting[]> | null = null

function tagIndex(): Map<string, Posting[]> {
  if (!postings) {
    postings = new Map()
    const add = (tag: string, p: Posting) => {
      const key = normalise(tag)
      if (!key) return
      const list = postings!.get(key)
      if (list) list.push(p)
      else postings!.set(key, [p])
    }
    for (const e of LORA_INDEX) {
      for (const t of e.triggers) {
        add(t.tag, { file: e.file, share: t.share, via: 'trigger', words: normalise(t.tag).split(' ').length })
      }
      for (const c of e.concepts) {
        add(c.tag, { file: e.file, share: c.share, via: 'concept', words: normalise(c.tag).split(' ').length })
      }
    }
  }
  return postings
}

/** Longest tag in the index is a few words, so n-grams above this cannot match. */
const MAX_NGRAM = 6

export type MatchOptions = {
  /** Keep only LoRAs trained for these bases. Omit to keep everything. */
  bases?: IndexedBase[]
  /** Drop matches below this score. Default 0.15, which cuts single incidental tags. */
  minScore?: number
  limit?: number
}

/**
 * Score every indexed LoRA against a prompt, by how much of its training
 * vocabulary the prompt actually uses.
 *
 * This is a lookup, not a model. It reads the prompt as written, so it knows
 * "spread pussy" matches lora-illustriousxl-improved-spread-pussy because that
 * tag is in 95 percent of its captions, and it knows nothing about what the
 * picture will look like. A captioner or a VLM would add that second half. This
 * half needs no model, no download and no server, and it is the half that is
 * exact: the tags are the LoRA's own words.
 *
 * Structural booru filler was stripped from `concepts` when the index was built,
 * so a prompt saying "1girl, solo, blonde hair" scores nothing here rather than
 * ranking all 39 equally. Anatomy words were NOT stripped: "pussy" and "nipples"
 * are poor trigger words but excellent evidence of which LoRA a prompt wants, and
 * the share weighting sorts a LoRA that saw them in 98 percent of its training
 * images above one that saw them in 30 percent.
 */
export function matchPrompt(prompt: string, options: MatchOptions = {}): LoraMatch[] {
  const words = normalise(prompt).split(' ').filter(Boolean)
  if (words.length === 0) return []
  const index = tagIndex()

  const perFile = new Map<string, Map<string, ConceptHit & { words: number }>>()
  for (let i = 0; i < words.length; i++) {
    for (let n = 1; n <= MAX_NGRAM && i + n <= words.length; n++) {
      const gram = words.slice(i, i + n).join(' ')
      const list = index.get(gram)
      if (!list) continue
      for (const p of list) {
        let hits = perFile.get(p.file)
        if (!hits) {
          hits = new Map()
          perFile.set(p.file, hits)
        }
        const existing = hits.get(gram)
        // A tag can be both a trigger and, in another LoRA, a concept. Within one
        // LoRA keep the stronger reading.
        if (!existing || (existing.via === 'concept' && p.via === 'trigger')) {
          hits.set(gram, { tag: gram, share: p.share, via: p.via, words: p.words })
        }
      }
    }
  }

  const wantBases = options.bases ? new Set(options.bases) : null
  const minScore = options.minScore ?? 0.15
  const out: LoraMatch[] = []
  for (const [file, hits] of perFile) {
    const entry = byFilename(file)
    if (!entry) continue
    if (wantBases && !wantBases.has(entry.base)) continue
    let score = 0
    const list: ConceptHit[] = []
    for (const h of hits.values()) {
      // A two word match is much less likely to be coincidence than a one word
      // match, so longer grams count for more.
      score += h.share * (1 + 0.5 * (h.words - 1)) * (h.via === 'trigger' ? 1.25 : 1)
      list.push({ tag: h.tag, share: h.share, via: h.via })
    }
    if (score < minScore) continue
    list.sort((a, b) => b.share - a.share)
    out.push({ entry, score: Number(score.toFixed(4)), hits: list })
  }
  out.sort((a, b) => b.score - a.score || a.entry.file.localeCompare(b.entry.file))
  return options.limit ? out.slice(0, options.limit) : out
}

/**
 * Free text search over triggers and concepts, for a picker's filter box.
 * Substring, so "nipple" finds "puffy nipples" and "nipples textures".
 */
export function searchConcepts(query: string, limit = 20): LoraMatch[] {
  const needle = normalise(query)
  if (!needle) return []
  const out: LoraMatch[] = []
  for (const entry of LORA_INDEX) {
    const hits: ConceptHit[] = []
    let score = 0
    for (const t of entry.triggers) {
      if (normalise(t.tag).includes(needle)) {
        hits.push({ tag: t.tag, share: t.share, via: 'trigger' })
        score += t.share * 1.25
      }
    }
    for (const c of entry.concepts) {
      if (normalise(c.tag).includes(needle)) {
        hits.push({ tag: c.tag, share: c.share, via: 'concept' })
        score += c.share
      }
    }
    if (hits.length === 0) continue
    hits.sort((a, b) => b.share - a.share)
    out.push({ entry, score: Number(score.toFixed(4)), hits })
  }
  out.sort((a, b) => b.score - a.score || a.entry.file.localeCompare(b.entry.file))
  return out.slice(0, limit)
}

/**
 * The tokens a chosen set of LoRAs needs in the prompt, deduplicated and with the
 * ones already present dropped. This is the call that converts the index into the
 * 1.313x, so it is the one worth wiring first.
 *
 * Only `promptTags` is used, so a LoRA with a minted token contributes that token
 * and not the author's whole caption template.
 *
 * `quality` triggers such as score_9 are included, because the LoRAs that carry
 * them really were trained with them, but they are the ones most likely to be in
 * a caller's preamble already, which is why the existing-prompt check matters.
 */
export function missingTriggers(files: string[], prompt: string): string[] {
  const have = ` ${normalise(prompt)} `
  const out: string[] = []
  const seen = new Set<string>()
  for (const file of files) {
    const entry = byFilename(file)
    if (!entry) continue
    for (const tag of entry.promptTags) {
      const key = normalise(tag)
      if (!key || seen.has(key)) continue
      seen.add(key)
      if (have.includes(` ${key} `)) continue
      out.push(tag)
    }
  }
  return out
}

