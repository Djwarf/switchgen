/**
 * Prompt text and booru tags spell the same idea differently: `spread_pussy`,
 * "spread pussy", "(spread pussy:1.2)". Everything is folded to lowercase words
 * separated by single spaces before comparison, and prompt weight syntax is
 * dropped, so the two vocabularies meet.
 */
function normalise(text: string): string {
  return text
    .toLowerCase()
    .replace(/[_]+/g, ' ')
    .replace(/[():]/g, ' ')
    .replace(/[^a-z0-9'\- ]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

let byFile: Map<string, LoraIndexEntry> | null = null

/**
 * Built on first use rather than at module load, because LORA_INDEX is declared
 * below this point and a top level build would read it before it exists.
 */
function fileMap(): Map<string, LoraIndexEntry> {
  if (!byFile) {
    byFile = new Map()
    for (const e of LORA_INDEX) {
      byFile.set(e.file, e)
      byFile.set(e.file.toLowerCase(), e)
      byFile.set(e.stem.toLowerCase(), e)
    }
  }
  return byFile
}

/** Look up one LoRA by its filename, with or without the .safetensors extension. */
export function byFilename(file: string): LoraIndexEntry | undefined {
  const map = fileMap()
  return map.get(file) ?? map.get(file.toLowerCase()) ?? map.get(file.toLowerCase().replace(/\.safetensors$/, ''))
}

/**
 * Every LoRA trained against one base. Pass several when a stack may cross inside
 * the SDXL lineage, for instance byBase('pony', 'illustrious', 'sdxl').
 */
export function byBase(...bases: IndexedBase[]): LoraIndexEntry[] {
  const want = new Set(bases)
  return LORA_INDEX.filter((e) => want.has(e.base))
}

/**
 * The LoRAs whose trigger is recoverable from their own file. `minConfidence`
 * defaults to 'likely', which excludes the extractions that rest on a folder name
 * or on thin captions. Pass 'weak' to see those too, and show their notes.
 */
export function withTrigger(minConfidence: 'strong' | 'likely' | 'weak' = 'likely'): LoraIndexEntry[] {
  const rank: Record<TriggerConfidence, number> = { strong: 3, likely: 2, weak: 1, none: 0, 'no-data': 0 }
  const floor = rank[minConfidence]
  return LORA_INDEX.filter((e) => e.triggers.length > 0 && rank[e.confidence] >= floor)
}

/** The LoRAs whose files carry nothing to read. Show these as "no trigger data", never as "no trigger". */
export function withoutTriggerData(): LoraIndexEntry[] {
  return LORA_INDEX.filter((e) => e.confidence === 'no-data')
}

/**
 * One sentence about a LoRA's trigger, safe to put in the UI as it stands.
 * Distinguishes "the file says there is no trigger" from "the file does not say",
 * which is the whole point of the confidence field.
 */
export function triggerNote(entry: LoraIndexEntry): string {
  switch (entry.confidence) {
    case 'strong':
      return `Trigger ${entry.triggerPhrase}, read from the training captions of ${entry.imageCount} images.`
    case 'likely':
      return `Trigger ${entry.triggerPhrase}, in ${Math.round((entry.triggers[0]?.share ?? 0) * 100)} percent of its training captions.`
    case 'weak':
      return `Probable trigger ${entry.triggerPhrase}, on weak evidence. ${entry.notes[0] ?? ''}`.trim()
    case 'none':
      return 'No trigger word. Its training captions carry nothing unique to it, so it works on weight alone.'
    case 'no-data':
      return 'No trigger data in the file. Whether it wants a trigger word is unknown, not none.'
  }
}

