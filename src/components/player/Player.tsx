/**
 * The clip viewer.
 *
 * A five-second clip costs minutes of a shared 16 GB card, so it is treated as
 * something to be studied: it never autoplays, it never loses your place, and
 * every number it prints can be trusted or is marked as approximate.
 *
 * Shape, per the build specification §9.1 — all chrome sits BELOW the frame as
 * a ruled caption block, never as a translucent overlay:
 *
 *     ┌──────────────┐
 *     │    video     │
 *     ├──────────────┤  1 px grey rule
 *     │  scrub rail  │
 *     │ frame ticks  │
 *     │  transport   │
 *     ├──────────────┤  1 px grey rule
 *     │   caption    │
 *     └──────────────┘
 *
 * Frame accuracy: seeks go to the midpoint of the target frame and the landed
 * frame is read back — from `requestVideoFrameCallback().mediaTime` where the
 * browser has it, from `currentTime` where it does not. A seek that misses is
 * nudged once; a second miss puts the player into relative stepping and prints
 * a dagger against the counter. It degrades to honest rather than to wrong.
 */

